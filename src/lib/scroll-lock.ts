/**
 * Блокировка прокрутки страницы под модальным окном.
 *
 * Казалось бы, хватило бы `body.style.overflow` прямо в компоненте — но окна
 * умеют открываться друг из друга: кнопка «Подать заявку» живёт внутри попапа
 * трека и сначала закрывает его. Уборка закрытого окна приходит отдельной
 * задачей (событие `close` у dialog асинхронное) и прилетает уже ПОСЛЕ того,
 * как новое окно поставило блокировку, — страница под открытым окном
 * оказывалась прокручиваемой.
 *
 * Поэтому считаем не «заблокировано / нет», а множество владельцев: снятие
 * чужой блокировки не трогает чужую. Заодно снятие становится идемпотентным —
 * компоненты прибираются дважды (по событию и явно), и это больше не вредит.
 */

const owners = new Set<Element>();

function apply(): void {
  document.body.style.overflow = owners.size > 0 ? 'hidden' : '';
}

export function lockScroll(owner: Element): void {
  owners.add(owner);
  apply();
}

export function unlockScroll(owner: Element): void {
  owners.delete(owner);
  apply();
}
